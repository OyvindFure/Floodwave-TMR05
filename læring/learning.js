function barge(){
  const svg = document.getElementById("bargeSvg"), sl = document.getElementById("bL");
  if(!svg || !sl) return;
  const css = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
  const X0 = 60, LAM = 300, Y0 = 120, AMP = 38, NS = "http://www.w3.org/2000/svg";
  function draw(){
    const wy = x => Y0 - AMP*Math.cos(2*Math.PI*(x - X0 - LAM/4)/LAM);   // topp midt over bargen ved L/λ = 1/2
    const r = parseFloat(sl.value), xe = X0 + r*LAM;
    document.getElementById("bOut").textContent = r.toFixed(2);
    const ink = css("--ink"), muted = css("--muted"), good = css("--good"), badc = css("--badc");
    const near = v => Math.abs(r - v) < 0.04;
    let pts = [];
    for(let x = 20; x <= 880; x += 4) pts.push(x+","+wy(x).toFixed(1));
    const yEnd = wy(xe);
    let ring = near(0.5) ? good : (near(1) ? badc : null);
    let s = '<line x1="20" y1="'+Y0+'" x2="880" y2="'+Y0+'" stroke="'+muted+'" stroke-dasharray="4 4" opacity=".6"/>'+
      '<rect x="'+X0+'" y="62" width="'+(r*LAM)+'" height="116" rx="4" fill="none" stroke="'+(ring||ink)+'" stroke-width="2.5"/>'+
      '<polyline points="'+pts.join(" ")+'" fill="none" stroke="'+badc+'" stroke-width="2.5"/>'+
      '<circle cx="'+X0+'" cy="'+wy(X0)+'" r="6" fill="'+badc+'"/>'+
      '<circle cx="'+xe+'" cy="'+yEnd+'" r="6" fill="'+badc+'"/>';
    if(ring) s += '<circle cx="'+xe+'" cy="'+yEnd+'" r="14" fill="none" stroke="'+ring+'" stroke-width="3"/>';
    // mål: lambda og L
    s += '<g stroke="'+muted+'" fill="'+muted+'" font-size="14" text-anchor="middle">'+
      '<line x1="'+X0+'" y1="205" x2="'+(X0+LAM)+'" y2="205" marker-start="" stroke-width="1.5"/>'+
      '<line x1="'+X0+'" y1="199" x2="'+X0+'" y2="211"/><line x1="'+(X0+LAM)+'" y1="199" x2="'+(X0+LAM)+'" y2="211"/>'+
      '<text x="'+(X0+LAM/2)+'" y="225" stroke="none">λ</text>'+
      '<line x1="'+X0+'" y1="236" x2="'+xe+'" y2="236" stroke="'+ink+'" stroke-width="1.5"/>'+
      '<line x1="'+X0+'" y1="230" x2="'+X0+'" y2="242" stroke="'+ink+'"/><line x1="'+xe+'" y1="230" x2="'+xe+'" y2="242" stroke="'+ink+'"/>'+
      '<text x="'+((X0+xe)/2)+'" y="249" stroke="none" fill="'+ink+'" dy="-14" transform="translate(0,14)">L</text></g>';
    svg.innerHTML = s;
    document.getElementById("bRead").innerHTML = near(0.5) ? SITE.t("lr.b_half") : (near(1) ? SITE.t("lr.b_one") : SITE.t("lr.b_none"));
  }
  sl.addEventListener("input", draw);
  window.addEventListener("themechange", draw);
  SITE.onLang(draw);
  draw();
}

function four(){
  const svg = document.getElementById("fourSvg");
  if(!svg) return;
  const css = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
  const M = [["Cecilie",48,"#2a78d6"],["Zhijun",32,"#1baf7a"],["Øyvind",24,"#eb6834"],["Anders",20,"#eda100"]];
  const LAM = 620, AMP = 18, CX = 450;
  function draw(){
    const w = 0.1;
    const ink = css("--ink"), muted = css("--muted"), sea = css("--accent");
    let s = "";
    M.forEach((m, k) => {
      const yc = 45 + k*84, r = m[1]*w*w/Math.PI, bw = r*LAM;
      let pts = [];
      for(let x = 10; x <= 890; x += 4) pts.push(x+","+(yc + AMP*Math.cos(2*Math.PI*(x-CX)/LAM)).toFixed(1));
      s += '<polyline points="'+pts.join(" ")+'" fill="none" stroke="'+sea+'" stroke-width="2.2"/>'+
           '<rect x="'+(CX-bw/2)+'" y="'+(yc+AMP-13)+'" width="'+bw+'" height="26" rx="2" fill="'+m[2]+'" fill-opacity=".22" stroke="'+m[2]+'" stroke-width="2.5"/>'+
           '<text x="14" y="'+(yc-26)+'" font-size="15" font-weight="600" fill="'+ink+'">'+m[0]+'</text>'+
           '<text x="'+(CX)+'" y="'+(yc-26)+'" font-size="14" text-anchor="middle" fill="'+muted+'">L/λ = '+r.toFixed(2)+'</text>';
    });
    svg.innerHTML = s;
  }
  window.addEventListener("themechange", draw);
  draw();
}

function topView(){
  const svg = document.getElementById("topSvg"), sl = document.getElementById("tL");
  if(!svg || !sl) return;
  const css = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
  const CX = 490, L = 340, W = 44, YT = 290, TOPY = 28;
  const xl = CX - L/2, xr = CX + L/2;
  // ein bølgjefront i avstand d frå bargen: venstre bue, rett stykke, høgre bue. Punkt med normal (nx,ny).
  function front(d, amp, lam, ph){
    const arc = Math.PI/2*d, tot = 2*arc + L, pts = [];
    const n = 140;
    for(let i = 0; i <= n; i++){
      const sI = tot*i/n; let x, y, nx, ny;
      if(sI < arc){ const t = Math.PI/2*(sI/arc); x = xl - d*Math.cos(t); y = YT - d*Math.sin(t); nx = -Math.cos(t); ny = -Math.sin(t); }
      else if(sI <= arc + L){ x = xl + (sI-arc); y = YT - d; nx = 0; ny = -1; }
      else { const t = Math.PI/2*((sI-arc-L)/arc); x = xr + d*Math.sin(t); y = YT - d + d*(1-Math.cos(t)); nx = Math.sin(t); ny = -Math.cos(t); }
      const w = amp*Math.sin(2*Math.PI*sI/lam + ph);
      pts.push([x + nx*w, y + ny*w, sI < arc ? 0 : (sI <= arc+L ? 1 : 2)]);
    }
    return pts;
  }
  function draw(){
    const w = parseFloat(sl.value), lam = 153*Math.pow(0.1/w, 0.55);   // skisse: kortare bølgje når ω̂ aukar
    document.getElementById("tOut").textContent = w.toFixed(2);
    document.getElementById("tRead").innerHTML = SITE.t(w <= 0.6 ? "lr.t_r1" : (w <= 1.1 ? "lr.t_r2" : "lr.t_r3"));
    const ink = css("--ink"), muted = css("--muted"), sea = css("--accent"), badc = css("--badc");
    const N = Math.floor((YT - TOPY)/lam);
    let s = '';
    for(let k = 1; k <= N; k++){
      const d = k*lam, op = Math.max(0.35, 1 - 0.05*k);
      // vrøvl aukar med kor mange bølgjelengder ein er ute frå bargen (skisse, ikkje utrekna)
      const amp = Math.min(0.20*lam, 0.9*Math.pow(Math.max(0, k-1.5), 1.4)*lam/20);
      const pts = front(d, amp, 0.9*lam + 6, k*1.7);
      [[0,sea],[1,ink],[2,sea]].forEach(([seg,col]) => {
        const p = pts.filter(q => q[2] === seg || (seg === 1 && false));
        // ta med nabopunkt så segmenta heng saman
        const idx = pts.map((q,i)=>q[2]===seg?i:-1).filter(i=>i>=0);
        const i0 = Math.max(0, idx[0]-1), i1 = Math.min(pts.length-1, idx[idx.length-1]+1);
        const path = pts.slice(i0, i1+1).map(q => q[0].toFixed(1)+","+q[1].toFixed(1)).join(" ");
        s += '<polyline points="'+path+'" fill="none" stroke="'+col+'" stroke-width="'+(seg===1?3.6:2.8)+'" stroke-linejoin="round" opacity="'+op+'"/>';
      });
    }
    s += '<rect x="'+xl+'" y="'+YT+'" width="'+L+'" height="'+W+'" rx="3" fill="'+ink+'" fill-opacity=".12" stroke="'+ink+'" stroke-width="2.5"/>'+
         '<text x="'+CX+'" y="'+(YT+W/2+5)+'" font-size="14" text-anchor="middle" fill="'+ink+'">'+SITE.t("lr.t_barge")+'</text>';
    if(N >= 1) s += '<text x="'+CX+'" y="'+(YT-lam-10)+'" font-size="13" text-anchor="middle" fill="'+ink+'">'+SITE.t("lr.t_side")+'</text>'+
         '<text x="'+(xr+lam*0.78+10)+'" y="'+(YT-lam*0.78-6)+'" font-size="13" fill="'+sea+'">'+SITE.t("lr.t_end")+'</text>';
    s += '<g fill="'+muted+'" stroke="'+muted+'" font-size="13">'+
         '<line x1="24" y1="'+(YT-8)+'" x2="24" y2="30" stroke-width="1.5"/><polygon points="24,22 19,34 29,34" stroke="none"/>'+
         '<text x="36" y="'+(YT-14)+'" stroke="none">'+SITE.t("lr.t_near")+'</text>'+
         '<text x="36" y="42" stroke="none">'+SITE.t("lr.t_far")+'</text>'+
         '<text x="36" y="110" stroke="none" font-size="12">'+SITE.t("lr.t_dist")+'</text></g>';
    svg.innerHTML = s;
  }
  sl.addEventListener("input", draw);
  window.addEventListener("themechange", draw);
  SITE.onLang(draw);
  draw();
}
