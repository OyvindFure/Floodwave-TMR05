function barge(){
  const svg = document.getElementById("bargeSvg"), sl = document.getElementById("bL");
  if(!svg || !sl) return;
  const css = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
  const X0 = 60, LAM = 300, Y0 = 120, AMP = 38, NS = "http://www.w3.org/2000/svg";
  function draw(){
    const wy = x => Y0 - AMP*Math.cos(2*Math.PI*(x - X0 - LAM/4)/LAM);   // topp midt over bargen ved L/λ = 1/2
    const r = parseFloat(sl.value), xe = X0 + r*LAM;
    document.getElementById("bOut").textContent = r.toFixed(2);
    const ink = css("--ink"), muted = css("--muted"), good = css("--good"), badc = css("--badc");
    const near = v => Math.abs(r - v) < 0.04;
    let pts = [];
    for(let x = 20; x <= 880; x += 4) pts.push(x+","+wy(x).toFixed(1));
    const yEnd = wy(xe);
    let ring = near(0.5) ? good : (near(1) ? badc : null);
    let s = '<line x1="20" y1="'+Y0+'" x2="880" y2="'+Y0+'" stroke="'+muted+'" stroke-dasharray="4 4" opacity=".6"/>'+
      '<rect x="'+X0+'" y="62" width="'+(r*LAM)+'" height="116" rx="4" fill="none" stroke="'+(ring||ink)+'" stroke-width="2.5"/>'+
      '<polyline points="'+pts.join(" ")+'" fill="none" stroke="'+badc+'" stroke-width="2.5"/>'+
      '<circle cx="'+X0+'" cy="'+wy(X0)+'" r="6" fill="'+badc+'"/>'+
      '<circle cx="'+xe+'" cy="'+yEnd+'" r="6" fill="'+badc+'"/>';
    if(ring) s += '<circle cx="'+xe+'" cy="'+yEnd+'" r="14" fill="none" stroke="'+ring+'" stroke-width="3"/>';
    // mål: lambda og L
    s += '<g stroke="'+muted+'" fill="'+muted+'" font-size="14" text-anchor="middle">'+
      '<line x1="'+X0+'" y1="205" x2="'+(X0+LAM)+'" y2="205" marker-start="" stroke-width="1.5"/>'+
      '<line x1="'+X0+'" y1="199" x2="'+X0+'" y2="211"/><line x1="'+(X0+LAM)+'" y1="199" x2="'+(X0+LAM)+'" y2="211"/>'+
      '<text x="'+(X0+LAM/2)+'" y="225" stroke="none">λ</text>'+
      '<line x1="'+X0+'" y1="236" x2="'+xe+'" y2="236" stroke="'+ink+'" stroke-width="1.5"/>'+
      '<line x1="'+X0+'" y1="230" x2="'+X0+'" y2="242" stroke="'+ink+'"/><line x1="'+xe+'" y1="230" x2="'+xe+'" y2="242" stroke="'+ink+'"/>'+
      '<text x="'+((X0+xe)/2)+'" y="249" stroke="none" fill="'+ink+'" dy="-14" transform="translate(0,14)">L</text></g>';
    svg.innerHTML = s;
    document.getElementById("bRead").innerHTML = near(0.5) ? SITE.t("lr.b_half") : (near(1) ? SITE.t("lr.b_one") : SITE.t("lr.b_none"));
  }
  sl.addEventListener("input", draw);
  window.addEventListener("themechange", draw);
  SITE.onLang(draw);
  draw();
}
SITE.start(barge);
